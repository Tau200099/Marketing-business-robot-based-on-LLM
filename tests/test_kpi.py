def test_table():
    for name, kind, fee, loaded, ug, u2, *want in CASES:
        k = compute(kind, fee, loaded, 1, ug, u2)
        got = [k.broadband, k.high, k.giga, k.pack, k.card]
        ok = all(abs(g - w) < 0.005 for g, w in zip(got, want))
        check(ok, f"#{name}：期望 {want}，实际 {[round(x, 3) for x in got]} {k.notes}")


def test_pack_formula():
    eq(round(pack_score(20, True), 2), 2.3, "10云盒 + 10智屏 = 2.3")
    eq(round(pack_score(10, True), 2), 1.3, "只办智屏10 = 1.3")
    eq(round(pack_score(25), 2), 2.5, "FTTR25 = 2.5")
    eq(round(pack_score(35), 2), 3.5, "10 + 25 = 3.5")
    eq(pack_score(0, True), 0.0, "没写钱 = 0（勾了智屏也不加）")


