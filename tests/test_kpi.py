def test_table():
    for name, kind, fee, loaded, *want in CASES:
        k = compute(kind, fee, loaded)
        got = [k.broadband, k.high, k.giga, k.pack, k.card]
        ok = all(abs(g - w) < 0.005 for g, w in zip(got, want))
        check(ok, f"#{name}：期望 {want}，实际 {[round(x, 3) for x in got]} {k.notes}")


def test_pack_formula():
    eq(round(pack_score([("智屏", 10), ("云盒", 10)]), 2), 5.01, "智屏10+云盒10 = 5.01")
    eq(round(pack_score([("智屏", 10)]), 2), 4.01, "只办智屏10 = 4.01")
    eq(round(pack_score([("智屏", 25)]), 2), 10.01, "只办智屏25 = 10.01")
    eq(round(pack_score([("FTTR", 25)]), 2), 2.51, "FTTR25 = 2.51")
    eq(round(pack_score([("看家", 9.9)]), 2), 1.0, "AI守护9.9 = 1")
    eq(round(pack_score([("看家", 9.9), ("看家", 9.9)]), 2), 1.99, "两个9.9 = 1.99（基准每单只用一次）")
    eq(pack_score([]), 0.0, "没有套包 = 0")


def test_notes():
    k = compute("新增", "239", "FTTR")
    check(any("FTTR" in n for n in k.notes), "FTTR 没写价钱会提醒核对")
    k = compute("存量", "云盒", "云盒")
    check(any("纯加装" in n for n in k.notes), "纯加装没写原档位，千五会提醒待核对")


def test_progress_composite():
    """功能说明 5.2 的例子：通惠累计（目标是编的）→ 综合 103.35%。【待领导核对算法】"""
    target = {"broadband": 20, "high": 15, "giga": 20, "pack": 30, "card": 10}
    done_ = {"broadband": 12, "high": 18.3, "giga": 30, "pack": 25.5, "card": 16}
    p = progress(done_, target)
    eq(round(p["high"], 3), 1.22, "中高套 122% 不封顶")
    eq(round(p["giga"], 2), 1.30, "千五 150% 封顶 130%")
    eq(round(p["card"], 2), 1.30, "单号卡 160% 封顶 130%")
    eq(round(composite(p) * 100, 2), 103.35, "综合 103.35%")
    eq(progress({"broadband": 5}, {"broadband": 0})["broadband"], 0.0, "目标 0 的进度记 0，不报错")


