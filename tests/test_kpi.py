def test_points_total():
    """09-29 用户定：价值积分看前后价值总和 —— 新增 = 写出来的钱都加上（含副宽）；存量 = 办完总和 − 原来总和；9.9 当 10。"""
    def pts(kind, fee):
        t = NEW_TEMPLATE.replace("存量", kind).replace("129改139 加10元云盒", fee)
        return parse_order(t)
    for kind, fee, want in (("新增", "199+副宽60", 259), ("新增", "199融合+60副宽", 259), ("新增", "199加10加25", 234),
                            ("新增", "10元云盒", 10), ("存量", "169改199+10", 40), ("存量", "169+9.9AI守护", 10),
                            ("存量", "199续约加副宽60", 60), ("存量", "139+10", 10), ("存量", "139续约", 0),
                            ("存量", "139改99+10", 0), ("新增", "780包年", 78), ("新增", "1390包年", 139),
                            ("新增", "1990包年", 199), ("新增", "390包年", 39), ("新增", "990包年", 99),
                            ("新增", "690包年", 69)):
        eq(pts(kind, fee).points, want, f"积分：{kind} {fee}")
    o = pts("新增", "10元云盒")
    eq((o.broadband, o.high, o.giga, o.box), (0, 0, 0, 1), "新增纯加装：活动群不记新增宽带，云盒记 1 个")
    # 09-30 回归测试：第一个数是档位的权益兑换照常算；只有权益金币数（699）没有档位的才标黄
    for kind, fee, want in (("新增", "239权益兑换FTTR", 239), ("新增", "239加699权益金兑换FTTR加10元云盒", 249),
                            ("存量", "199续约权益兑换FTTR", 0)):
        o = pts(kind, fee)
        eq((o.points, o.needs_review), (want, False), f"权益兑换带档位：{kind} {fee} 积分 {want}、不标黄")
    o = pts("存量", "199续约权益兑换FTTR")
    eq(o.renew, 1, "存量 199续约权益兑换FTTR：长续约 1")
    o = pts("存量", "699权益兑换FTTR")
    check(o.needs_review and "权益" in o.note, "只有权益金币数、没有档位：照旧标黄请核对")


def test_progress_composite():
    """功能说明 5.2 的例子：通惠累计（目标是编的）→ 综合 103.35%。"""
    target = {"broadband": 20, "high": 15, "giga": 20, "pack": 30, "card": 10}
    done_ = {"broadband": 12, "high": 18.3, "giga": 30, "pack": 25.5, "card": 16}
    p = progress(done_, target)
    eq(round(p["high"], 3), 1.22, "中高套 122% 不封顶")
    eq(round(p["giga"], 2), 1.30, "千五 150% 封顶 130%")
    eq(round(p["card"], 2), 1.30, "单号卡 160% 封顶 130%")
    eq(round(composite(p) * 100, 2), 103.35, "综合 103.35%")
    eq(round(progress({"broadband": 30}, {"broadband": 20})["broadband"], 2), 1.30, "宽带 150% 也封顶 130%（09-30 通知）")
    eq(round(progress({"high": 30}, {"high": 20})["high"], 2), 1.50, "中高套 150% 不封顶")
    # 通惠真实目标（附件一）：宽带 20/39、中高套 9/15、千五 40/33→121.2%、套包 30/48、号卡 10/32 → 67.56%
    real = {"broadband": 39, "high": 15, "giga": 33, "pack": 48, "card": 32}
    got = {"broadband": 20, "high": 9, "giga": 40, "pack": 30, "card": 10}
    eq(round(composite(progress(got, real)) * 100, 2), 67.56, "通惠真实目标的例子：综合 67.56%")
    eq(progress({"broadband": 5}, {"broadband": 0})["broadband"], 0.0, "目标 0 的进度记 0，不报错")


