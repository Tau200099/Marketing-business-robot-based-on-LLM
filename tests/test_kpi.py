    eq(o.fee, "239+25元FTTR", "挤一行：套餐截到下一个字段名，尾巴的 emoji 去掉")
    eq((o.loaded, o.up_giga, o.up_2000), ("FTTR", "否", "是"), "挤一行：几栏不串格")
